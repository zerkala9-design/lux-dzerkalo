export function getCategory(key: string): Category | undefined {
  return categories.find((c) => c.key === key);
}

export function getCategoryBySlug(slug: string): Category | undefined {
  return categories.find((c) => c.slug === slug);
}

/** Локалізовані поля категорії */
export function catTitle(c: Category, lang: Lang) {
  return lang === 'ru' ? c.title_ru : c.title;
}
export function catShort(c: Category, lang: Lang) {
  return lang === 'ru' ? c.short_ru : c.short;
}
export function catDescription(c: Category, lang: Lang) {
  return lang === 'ru' ? c.description_ru : c.description;
}
